# Generates the adaptive-icon foreground (vector drawable) and an SVG twin for previewing, from one
# set of shapes so the trail always lines up with the rock.
# Usage: python3 -I tools/launcher-icon.py app/src/main/res/drawable/ic_launcher_foreground.xml preview.svg
#        google-chrome --headless=new --screenshot=preview.png --window-size=432,432 file://$PWD/preview.svg
import math
C = (63.0, 47.5); R = 6.5
d = (-0.62, 0.78); n = math.hypot(*d); d = (d[0] / n, d[1] / n)     # direction of travel
p = (d[1], -d[0])                                                    # perpendicular
def at(base, along, side):  # point = base - d*along + p*side
    return (base[0] - d[0] * along + p[0] * side, base[1] - d[1] * along + p[1] * side)
def f(pt): return f'{pt[0]:.2f},{pt[1]:.2f}'
def tail(length, half, bow):
    b1, b2 = at(C, 0, half), at(C, 0, -half)
    a = at(C, length, 0)
    c1, c2 = at(C, length * 0.45, half * bow), at(C, length * 0.45, -half * bow)
    return f'M{f(b1)} Q{f(c1)} {f(a)} Q{f(c2)} {f(b2)} Z', a
outer, a_outer = tail(48, R * 1.05, 0.38)
inner, a_inner = tail(26, R * 0.45, 0.4)
fade_outer = at(C, 30, 0)  # the trail is gone well before its tip
fade_inner = at(C, 18, 0)
hot = at(C, -2.6, 0)  # the white-hot face, toward the direction of travel
def circle(c, r): return f'M{c[0]-r:.2f},{c[1]:.2f} a{r},{r} 0 1,0 {2*r},0 a{r},{r} 0 1,0 {-2*r},0 Z'
earth_glow = 'M-24,100 a56,56 0 1,0 112,0 a56,56 0 1,0 -112,0 Z'
earth = 'M-20,100 a52,52 0 1,0 104,0 a52,52 0 1,0 -104,0 Z'

# (path, gradient) — gradient: ('linear', x1,y1,x2,y2, c1, c2) or ('radial', cx,cy,r, c1, c2); colours #AARRGGBB
layers = [
    (earth_glow, ('radial', 32, 100, 58, '#3368C6FF', '#0068C6FF')),
    (earth, ('linear', 20, 50, 40, 100, '#FF2F86E8', '#FF0A2350')),
    (earth, ('stroke', '#B37CC4FF', 1.4)),
    (outer, ('linear', *C, *fade_outer, '#F2FF7A1A', '#00FF5A10')),
    (inner, ('linear', *C, *fade_inner, '#FFFFE2B0', '#00FFD08A')),
    (circle(C, R * 1.75), ('radial', *C, R * 1.75, '#88FF9A3C', '#00FF9A3C')),
    (circle(C, R), ('radial', *hot, R * 1.25, '#FFFFF4DC', '#FFFF7A1A')),
]

def android_color(c): return c
def xml():
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- The wallpaper in one glance: the Earth\'s limb low on the left and a burning meteor diving in',
           '     from the upper right, its trail along its line of flight. 108 dp adaptive-icon canvas; the',
           '     meteor sits inside the 66 dp safe zone. Generated by tools/launcher-icon.py: edit the script, not this file. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    xmlns:aapt="http://schemas.android.com/aapt"',
           '    android:width="108dp"', '    android:height="108dp"',
           '    android:viewportWidth="108"', '    android:viewportHeight="108">']
    for path, g in layers:
        if g[0] == 'stroke':
            out.append(f'    <path android:pathData="{path}" android:strokeColor="{g[1]}" android:strokeWidth="{g[2]}" />')
            continue
        out.append(f'    <path android:pathData="{path}">')
        out.append('        <aapt:attr name="android:fillColor">')
        if g[0] == 'linear':
            _, x1, y1, x2, y2, c1, c2 = g
            out.append(f'            <gradient android:type="linear" android:startX="{x1:.2f}" android:startY="{y1:.2f}"')
            out.append(f'                android:endX="{x2:.2f}" android:endY="{y2:.2f}" android:startColor="{c1}" android:endColor="{c2}" />')
        else:
            _, cx, cy, r, c1, c2 = g
            out.append(f'            <gradient android:type="radial" android:centerX="{cx:.2f}" android:centerY="{cy:.2f}"')
            out.append(f'                android:gradientRadius="{r:.2f}" android:startColor="{c1}" android:endColor="{c2}" />')
        out.append('        </aapt:attr>')
        out.append('    </path>')
    out.append('</vector>')
    return '\n'.join(out) + '\n'

def svg(size=432, mask=True):
    def rgba(c):
        a = int(c[1:3], 16) / 255; return f'#{c[3:]}', a
    defs, body = [], []
    for i, (path, g) in enumerate(layers):
        if g[0] == 'stroke':
            c, a = rgba(g[1])
            body.append(f'<path d="{path}" fill="none" stroke="{c}" stroke-opacity="{a:.3f}" stroke-width="{g[2]}"/>')
            continue
        (c1, a1), (c2, a2) = rgba(g[-2]), rgba(g[-1])
        stops = f'<stop offset="0" stop-color="{c1}" stop-opacity="{a1:.3f}"/><stop offset="1" stop-color="{c2}" stop-opacity="{a2:.3f}"/>'
        if g[0] == 'linear':
            _, x1, y1, x2, y2, *_ = g
            defs.append(f'<linearGradient id="g{i}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">{stops}</linearGradient>')
        else:
            _, cx, cy, r, *_ = g
            defs.append(f'<radialGradient id="g{i}" gradientUnits="userSpaceOnUse" cx="{cx}" cy="{cy}" r="{r}">{stops}</radialGradient>')
        body.append(f'<path d="{path}" fill="url(#g{i})"/>')
    clip = '<clipPath id="m"><circle cx="54" cy="54" r="36"/></clipPath>' if mask else ''
    g_open = '<g clip-path="url(#m)">' if mask else '<g>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">'
            f'<defs>{"".join(defs)}{clip}</defs>{g_open}<rect x="0" y="0" width="108" height="108" fill="#05070F"/>'
            f'{"".join(body)}</g></svg>')

import sys
open(sys.argv[1], 'w').write(xml())
open(sys.argv[2], 'w').write(svg())
